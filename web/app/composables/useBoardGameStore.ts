// Matches the status CHECK constraint on public.booking in supabase/schema.sql
export type BookingStatus = 'Reserved' | 'In_Use' | 'Overdue' | 'Returned' | 'Cancelled'

// Matches the condition_status CHECK constraint on public.game_copy
export type CopyCondition = 'Good' | 'Fair' | 'Damaged' | 'Lost'

export const CONDITION_LABELS: Record<CopyCondition, string> = {
  Good: 'ดี',
  Fair: 'พอใช้',
  Damaged: 'ชำรุด',
  Lost: 'สูญหาย'
}

/** Upper bound for one "add boxes" action, to catch a mistyped extra zero. */
export const MAX_COPIES_PER_ADD = 20

export interface Copy {
  id: string
  label: string
  number: number
  condition: CopyCondition
}

/**
 * Damaged or lost boxes stay on record — bookings reference them and the FK is
 * ON DELETE RESTRICT — but they are not offered to customers.
 */
export function isUsableCopy(copy: Copy) {
  return copy.condition === 'Good' || copy.condition === 'Fair'
}

export interface Category {
  id: string
  name: string
}

export interface Game {
  id: string
  name: string
  description: string
  icon: string
  image?: string
  category: string
  categoryId: string | null
  minP: number
  maxP: number
  playtime: number
  /** Every box on record, including retired ones; customers should use usableCopies(). */
  copies: Copy[]
  howToPlay: string[]
}

/** The editable fields of public.board_game plus its (single) category link. */
export interface GameInput {
  name: string
  description: string
  minP: number
  maxP: number
  playtime: number
  categoryId: string | null
}

/** Mirrors public.users. user_id is generated by the system — nobody types it. */
