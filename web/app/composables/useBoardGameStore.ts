let bookingSeq = 1
function nextBookingId() {
  return 'BK-' + String(bookingSeq++).padStart(3, '0')
}

let userSeq = 1
function nextUserId() {
  return 'U' + String(userSeq++).padStart(3, '0')
}

function normalizeEmail(email: string) {
  return email.trim().toLowerCase()
}

function normalizePhone(phone: string) {
  return phone.replace(/[^0-9]/g, '')
}

function overlaps(aStart: Date, aEnd: Date, bStart: Date, bEnd: Date) {
  return aStart < bEnd && bStart < aEnd
}

let store: ReturnType<typeof createStore> | null = null

function createStore() {
  const simNow = ref(new Date())
  const users = reactive<User[]>([])
  const bookings = reactive<Booking[]>([])

  function todayAt(h: number, m: number) {
    const d = new Date(simNow.value)
    d.setHours(h, m, 0, 0)
    return d
  }

  /** Email is the identity: booking again with the same address reuses the same USERS row. */
  function findOrCreateUser(input: Pick<BookingInput, 'firstName' | 'lastName' | 'email' | 'phone'>) {
    const email = normalizeEmail(input.email)
    const existing = users.find(u => u.email === email)
    if (existing) return existing
    const user: User = {
      id: nextUserId(),
      firstName: input.firstName.trim(),
      lastName: input.lastName.trim(),
      email,
      phone: normalizePhone(input.phone)
    }
    users.push(user)
    return user
  }

  function seedData() {
    const push = (gameId: string, copyId: string, first: string, last: string, email: string, phone: string,
      sh: number, sm: number, eh: number, em: number, status: BookingStatus) => {
      const user = findOrCreateUser({ firstName: first, lastName: last, email, phone })
      bookings.push({
        id: nextBookingId(),
        gameId, copyId, userId: user.id,
        start: todayAt(sh, sm), end: todayAt(eh, em),
        status, actualReturn: null
      })
    }
    const nowH = simNow.value.getHours()
    push('catan', 'CATAN-01', 'สมชาย', 'ใจดี', 'somchai@example.com', '0812345678', Math.max(0, nowH - 2), 0, nowH, 0, 'In_Use')
    push('catan', 'CATAN-02', 'พิมพ์ชนก', 'แซ่ตั้ง', 'pimchanok@example.com', '0823456789', nowH + 1, 15, nowH + 3, 15, 'Reserved')
    push('splendor', 'SPLEN-01', 'ธนกร', 'ศรีสุข', 'thanakorn@example.com', '0834567890', nowH + 2, 0, nowH + 2, 45, 'Reserved')
    push('sushi', 'SUSHI-01', 'กมลชนก', 'ทองดี', 'kamonchanok@example.com', '0845678901', Math.max(0, nowH - 1), 0, nowH + 0, 30, 'In_Use')
    push('codenames', 'CODE-01', 'ภูผา', 'เอกจิตร', 'phupha@example.com', '0856789012', nowH + 4, 0, nowH + 5, 0, 'Reserved')
  }

  function getUser(userId: string) {
    return users.find(u => u.id === userId)
  }

  function userLabel(userId: string) {
    const u = getUser(userId)
    return u ? `${u.firstName} ${u.lastName}` : '—'
  }

  function activeBookingsForUser(userId: string) {
    return bookings.filter(b => b.userId === userId && (b.status === 'Reserved' || b.status === 'In_Use'))
  }

  function hasOverdue(userId: string) {
    return bookings.some(b => b.userId === userId && b.status === 'Overdue')
  }

  function validateBooking({ firstName, lastName, email, phone, copyId, start, end }: BookingInput): string | null {
    if (!firstName.trim() || !lastName.trim()) return 'กรุณากรอกชื่อและนามสกุล'
    if (!email.trim()) return 'กรุณากรอกอีเมล'
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.trim())) return 'รูปแบบอีเมลไม่ถูกต้อง'
    const digits = normalizePhone(phone)
    if (digits && (digits.length < 9 || digits.length > 10)) return 'เบอร์โทรต้องมี 9-10 หลัก'
    if (!(start instanceof Date) || !(end instanceof Date) || isNaN(+start) || isNaN(+end)) return 'กรุณาระบุช่วงเวลาให้ถูกต้อง'
    if (end <= start) return 'เวลาสิ้นสุดต้องอยู่หลังเวลาเริ่ม'
    const mins = (end.getTime() - start.getTime()) / 60000
    if (mins < 30) return 'ระยะเวลาการจองต้องอย่างน้อย 30 นาที (BR-02)'
    if (mins > 240) return 'ระยะเวลาการจองต้องไม่เกิน 4 ชั่วโมง (BR-02)'

    // BR-01/BR-04 apply per person; an unseen email is a brand-new user with no history.
    const existing = users.find(u => u.email === normalizeEmail(email))
    if (existing) {
      if (hasOverdue(existing.id)) return 'คุณมีรายการค้างสถานะ Overdue โปรดคืนเกมก่อนจองใหม่ (BR-04)'
      if (activeBookingsForUser(existing.id).length >= 2) return 'คุณมีรายการจองที่ใช้งาน/รอใช้งานอยู่แล้ว 2 รายการ (BR-01)'
    }

    const conflict = bookings.some(b => b.copyId === copyId
      && (b.status === 'Reserved' || b.status === 'In_Use' || b.status === 'Overdue')
      && overlaps(start, end, b.start, b.end))
    if (conflict) return 'ช่วงเวลานี้ถูกจองเต็มแล้ว (BR-03)'
    return null
  }

  function recomputeOverdue() {
    bookings.forEach(b => {
      if (b.status === 'In_Use' && simNow.value > b.end) b.status = 'Overdue'
    })
  }

  function copyStatus(copy: Copy): 'free' | 'busy' {
    const blocking = bookings.some(b => b.copyId === copy.id && (b.status === 'In_Use' || b.status === 'Overdue'))
    return blocking ? 'busy' : 'free'
  }

  function getGame(gameId: string) {
    return games.find(g => g.id === gameId)
  }

  function freeCopyCount(game: Game) {
    return game.copies.filter(c => copyStatus(c) === 'free').length
  }

  function bookingsForCopy(copyId: string) {
    return bookings
      .filter(b => b.copyId === copyId && b.status !== 'Returned' && b.status !== 'Cancelled')
      .sort((a, b) => +a.start - +b.start)
  }

  function addBooking(input: BookingInput) {
    const error = validateBooking(input)
    if (error) return { error }
    const user = findOrCreateUser(input)
    bookings.push({
      id: nextBookingId(),
      gameId: input.gameId,
      copyId: input.copyId,
      userId: user.id,
      start: input.start,
      end: input.end,
      status: 'Reserved',
      actualReturn: null
    })
    return { error: null }
  }

  function markInUse(id: string) {
    const b = bookings.find(x => x.id === id)
    if (b) b.status = 'In_Use'
    return b
  }

  function markReturned(id: string) {
    const b = bookings.find(x => x.id === id)
    if (b) {
      b.status = 'Returned'
      b.actualReturn = new Date(simNow.value)
    }
    return b
  }

  /**
   * The clock follows the device's real local time. Setting it by hand pauses that
   * (so an Overdue state can be demonstrated) until resetToRealTime() is called.
   */
  const isTimeOverridden = ref(false)

  function syncToRealTime() {
    if (isTimeOverridden.value) return
    simNow.value = new Date()
    recomputeOverdue()
  }

  function setSimNow(d: Date) {
    isTimeOverridden.value = true
    simNow.value = d
    recomputeOverdue()
  }

  function resetToRealTime() {
    isTimeOverridden.value = false
    simNow.value = new Date()
    recomputeOverdue()
  }

  seedData()

  return {
    games,
    users,
    bookings,
    getUser,
    userLabel,
    simNow,
    isTimeOverridden,
    todayAt,
    copyStatus,
    getGame,
    freeCopyCount,
    bookingsForCopy,
    addBooking,
    markInUse,
    markReturned,
    setSimNow,
    syncToRealTime,
    resetToRealTime,
    recomputeOverdue
  }
}

export function useBoardGameStore() {
  if (!store) store = createStore()
  return store
}
