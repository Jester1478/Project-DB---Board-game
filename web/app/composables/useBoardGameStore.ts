import { reactive, ref } from 'vue'

// Matches the Status CHECK constraint on the BOOKING table in supabase/schema.sql
export type BookingStatus = 'Reserved' | 'In_Use' | 'Overdue' | 'Returned' | 'Cancelled'

export interface Copy {
  id: string
  label: string
}

export interface Game {
  id: string
  name: string
  icon: string
  /** Path to a real image, e.g. '/games/catan.jpg' (file lives in web/public/games/). Falls back to `icon` when unset or the file is missing. */
  image?: string
  category: string
  minP: number
  maxP: number
  playtime: number
  copies: Copy[]
  howToPlay: string[]
}

/** Mirrors the USERS table. User_ID is generated by the system — nobody types it. */
export interface User {
  id: string
  firstName: string
  lastName: string
  email: string
  phone: string
}

export interface Booking {
  id: string
  gameId: string
  copyId: string
  userId: string
  start: Date
  end: Date
  status: BookingStatus
  actualReturn: Date | null
}

export interface BookingInput {
  firstName: string
  lastName: string
  email: string
  phone: string
  gameId: string
  copyId: string
  start: Date
  end: Date
}

